import fs from 'node:fs';
const root = new URL('../', import.meta.url);
let svg=fs.readFileSync(new URL('handoff/svg/border-compact.svg',root),'utf8');
svg=svg.replace(/<rect\b[^>]*fill="#F5F5F5"[^>]*\/>/g,'').replace(/\s+id="[^"]*"/g,'').replace(/([a-z]+)-([a-z]+)=/g,(_,a,b)=>a+b[0].toUpperCase()+b.slice(1)+'=').replace(/"#E8C99B"/gi,'{color("color/line/wire")}').replace('<svg ', '<svg style={{position:"absolute",inset:0,pointerEvents:"none",zIndex:100}} ');
fs.writeFileSync(new URL('dashboard/CompactBorder.tsx',root),'// Generated by tools/svg_to_tsx.mjs.\nimport React from "react";\nimport {color} from "../tokens";\nexport function CompactBorder(){return ('+svg.trim()+');}\n');

// CardBorder: the same border with the five-tier notch of the pre-Stage card border at the top and
// bottom centre, for scenes without the map. The notch geometry and its collapse/expand animation
// live in dashboard/notch.tsx; `notch` runs from 0 (straight wire) to 1 (full notch).
let card=svg;
for(const [y0,dir] of [[20,1],[1060,-1]]){
 const wire=`d="M786.059 ${y0}H1133.94"`;
 if(!card.includes(wire))throw new Error(`CardBorder: centre wire ${wire} not found in border-compact.svg`);
 card=card.replace(wire,`d={notchPath(${y0},${dir},notch)}`);
}
fs.writeFileSync(new URL('dashboard/CardBorder.tsx',root),'// Generated by tools/svg_to_tsx.mjs.\nimport React from "react";\nimport {color} from "../tokens";\nimport {notchPath} from "./notch";\nexport function CardBorder({notch=1}:{notch?:number}){return ('+card.trim()+');}\n');
