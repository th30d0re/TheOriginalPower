// CardBorder: the same border with the five-tier notch of the pre-Stage card border at the top and
// bottom centre, for scenes without the map. Old notch measured from runs/S00-01 (3 px stroke),
// scaled 0.8 to match the compact border's coils and drawn at its 1.6 px wire stroke.
const r=n=>+n.toFixed(2);
function notch(y0,dir){
 const cx=960,kink=62.4,apex=10.7,depth=48,bars=[[7.8,40.9],[17.4,32.8],[27,24.9],[36.6,16.9]],y=d=>r(y0+dir*d);
 return `M786.059 ${y0}H${r(cx-kink)}L${r(cx-apex)} ${y(depth)}M${r(cx+apex)} ${y(depth)}L${r(cx+kink)} ${y0}H1133.94`+bars.map(([d,h])=>`M${r(cx-h)} ${y(d)}H${r(cx+h)}`).join('');
}
let card=svg;
for(const [y0,dir] of [[20,1],[1060,-1]]){
 const wire=`d="M786.059 ${y0}H1133.94"`;
 if(!card.includes(wire))throw new Error(`CardBorder: centre wire ${wire} not found in border-compact.svg`);
 card=card.replace(wire,`d="${notch(y0,dir)}"`);
}
fs.writeFileSync(new URL('dashboard/CardBorder.tsx',root),'// Generated by tools/svg_to_tsx.mjs.\nimport React from "react";\nimport {color} from "../tokens";\nexport function CardBorder(){return ('+card.trim()+');}\n');
